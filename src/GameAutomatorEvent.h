#ifndef __WmeGameAutomatorEvent_H__
#define __WmeGameAutomatorEvent_H__


#include "BScriptable.h"
#include "dctypes.h"	

/**
* Source of the engine event.
*/
enum class GameAutomatorEventSource 
{ 
NONE,  /*!< none */
ACTOR, /*!< actor */
SCENE, /*!< scene */
ENTITY, /*!< entity */
BUTTON, /*!< button */
SETPROPERTY, /*!< setproperty */
WINDOW, /*!< window */
STORE, /*!< store */
OBJECT /*!< object */
};

/**
* Type of the engine event.
*/
enum class GameAutomatorEventType 
{ 
NONE, /*!< none */
GOTO, /*!< goto */
TURNTO, /*!< turnto */
TALK, /*!< talk */
CHANGE, /*!< change */
PRESS, /*!< press */
INTERACTIVE, /*!< interactive */
PLAYANIM, /*!< playanim */
TAKEITEM, /*!< takeitem */
GETRESPONSE, /*!< getresponse */
SYSEXCLUSIVE, /*!< sysexclusive */
STOREEVENT, /*!< storeevent */
READY /*!< ready */
};

/**
* The constructors list all events that are generated by the engine.
*/
class GameAutomatorEvent : public CBScriptable
{
public:
        /**
         * @param source - ::GameAutomatorEventSource
         * @param type - ::GameAutomatorEventType
         * @param name - Name field of the event
         * 
         * Called directly from:
         * 
         * <b>CAdObject::ScCallMethod(CScScript* Script, CScStack *Stack, CScStack *ThisStack, char *Name)</b> for script method call <b>"TakeItem"</b>.
         *
         * <b>CUIWindow::ScCallMethod(CScScript* Script, CScStack *Stack, CScStack *ThisStack, char *Name)</b> for script method call <b>"GoSystemExclusive"</b>.
		 *
		 * <b>CSXStore::ReceiveProductsEnd()</b> for event <b>"ProductsValidated"</b>.
		 *
		 * <b>CSXStore::OnRestoreFinished(bool error)</b> for events <b>"TransactionsRestoreFailed"</b> resp <b>"TransactionsRestoreFinished"</b>.
		 *
		 * <b>CSXStore::ReceiveTransactionsEnd()</b> for event <b>"TransactionsUpdated"</b>.
		 *
		 * <b>CAdObject::triggerGameAutomatorCallback()</b> for event <b>"Object is ready"</b>.
         *
	  * This generic constructor is also implicitly called by all other specific ctors.
	  */
	GameAutomatorEvent(CBGame* inGame, GameAutomatorEventSource source, GameAutomatorEventType type, char* name) :
		CBScriptable(inGame), m_Source(source), m_Type(type) {
		m_Name = new AnsiString(name);
	}
	
        /**
         * @param source - ::GameAutomatorEventSource
         * @param type - ::GameAutomatorEventType
         * @param name - Name field of the event
         * @param turntoDir - ::TDirection value of the event
         * 
         * Called directly from:
         * 
         * <b>CAdActor::TurnTo(TDirection dir)</b>
	  */
	GameAutomatorEvent(CBGame* inGame, GameAutomatorEventSource source, GameAutomatorEventType type, char* name, TDirection turntoDir) :
		GameAutomatorEvent(inGame, source, type, name) {
		m_TurntoDir = turntoDir;
	}
	
        /**
         * @param source - ::GameAutomatorEventSource
         * @param type - ::GameAutomatorEventType
         * @param name - Name field of the event
         * @param X - X coordinate of event
         * @param Y - Y coordinate of event
         * 
         * Called directly from:
         * 
         * <b>CAdActor::GoTo(int X, int Y, TDirection AfterWalkDir)</b>
	  */
	GameAutomatorEvent(CBGame* inGame, GameAutomatorEventSource source, GameAutomatorEventType type, char* name, int X, int Y) :
		GameAutomatorEvent(inGame, source, type, name) {
		m_X = X;
		m_Y = Y;
	}

	 /**
         * @param source - ::GameAutomatorEventSource
         * @param type - ::GameAutomatorEventType
         * @param name - Name field of the event
         * @param text - Text field of event
         * 
         * Called directly from:
         * 
         * <b>CAdObject::Talk(char *Text, char* Sound, DWORD Duration, char *Stances, TTextAlign Align)</b>
         *
         * <b>CAdGame::ChangeScene(char *Filename, bool FadeIn)</b>
         *
         * <b>CUIButton::Press()</b>
         *
         * <b>CAdObject::PlayAnim(char* Filename)</b>
	  */
	GameAutomatorEvent(CBGame* inGame, GameAutomatorEventSource source, GameAutomatorEventType type, char* name, char* text) :
		GameAutomatorEvent(inGame, source, type, name) {
		m_Sentence = new AnsiString(text);
	}
	
	 /**
         * @param source - ::GameAutomatorEventSource
         * @param type - ::GameAutomatorEventType
         * @param name - Name field of the event
         * @param interactive - Game.Interactive value
         * 
         * Called directly from:
         * 
         * <b>CBGame::ScSetProperty(char *Name, CScValue *Value)</b> for setting property <b>Game.Interactive</b>.
	  */
	GameAutomatorEvent(CBGame* inGame, GameAutomatorEventSource source, GameAutomatorEventType type, char* name, bool interactive) :
		GameAutomatorEvent(inGame, source, type, name)  {
		m_Interactive = interactive;
	}

	/**
	* Copy constructor to create an element to be passed around in scripts.
	* Must include repetitions for a 1:1 copy.
	*/
	GameAutomatorEvent(const GameAutomatorEvent& orig)
		: CBScriptable(orig.Game), m_Source(orig.m_Source), m_Type(orig.m_Type), 
		m_Sentence(orig.m_Sentence), m_TurntoDir(orig.m_TurntoDir), m_X(orig.m_X), m_Y(orig.m_Y),
		m_Interactive(orig.m_Interactive), m_Repetitions(orig.m_Repetitions)
	{ 
		m_Name = new AnsiString(orig.m_Name->c_str());
		if (orig.m_Sentence != NULL)
		{
			m_Sentence = new AnsiString(orig.m_Sentence->c_str());
		}
		else
		{
			m_Sentence = NULL;
		}
	}

	// delete all unused constructors and assignment operators explicitly, just in case...
	GameAutomatorEvent(const GameAutomatorEvent&& orig) = delete;
	GameAutomatorEvent& operator=(const GameAutomatorEvent& orig) = delete;
	GameAutomatorEvent& operator=(GameAutomatorEvent&& orig) = delete;
	
	void addRepetition(void) { m_Repetitions++; }

	friend bool operator==(const GameAutomatorEvent& lhs, const GameAutomatorEvent& rhs);

	~GameAutomatorEvent() {
		delete m_Name;
		if (m_Sentence != NULL) delete m_Sentence;
	}

	virtual CScValue* ScGetProperty(char* Name);
	virtual HRESULT ScSetProperty(char *Name, CScValue *Value);
	virtual HRESULT ScCallMethod(CScScript* Script, CScStack *Stack, CScStack *ThisStack, char *Name);
	virtual char* ScToString();

private:
	const GameAutomatorEventSource m_Source;
	const GameAutomatorEventType   m_Type;
	AnsiString* m_Name;
	AnsiString* m_Sentence = NULL;
	TDirection m_TurntoDir = DI_NONE;
	int m_X = 0;
	int m_Y = 0;
	bool m_Interactive = true;
	int m_Repetitions = 0;
};

#endif
